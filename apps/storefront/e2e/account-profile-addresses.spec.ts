import { expect, test } from "@playwright/test"
import { generateTestEmail, generateTestPassword } from "./test-helpers"

test("customer can update profile and manage saved addresses", async ({ page }) => {
  test.setTimeout(120_000)
  const email = generateTestEmail("profile-address")

  await page.goto("/vn/account")
  await page.getByTestId("register-button").click()
  const register = page.getByTestId("register-page")
  await expect(register).toBeVisible()
  await register.getByTestId("first-name-input").fill("Test")
  await register.getByTestId("last-name-input").fill("Customer")
  await register.getByTestId("email-input").fill(email)
  await register.getByTestId("phone-input").fill("0901234567")
  await register.getByTestId("password-input").fill(generateTestPassword())
  await register.locator('button[type="submit"]').click()
  await expect(page.getByTestId("overview-page-wrapper")).toBeVisible({ timeout: 20_000 })

  await page.goto("/vn/account/profile")
  await expect(page.getByTestId("profile-page-wrapper")).toBeVisible()
  const nameEditor = page.getByTestId("account-name-editor")
  await nameEditor.getByTestId("edit-button").click()
  await nameEditor.getByTestId("first-name-input").fill("Quy")
  await nameEditor.getByTestId("last-name-input").fill("Regression")
  await nameEditor.getByTestId("save-button").click()
  await expect(nameEditor.getByTestId("success-message")).toBeVisible()
  await page.reload()
  await expect(page.getByTestId("account-name-editor").getByTestId("current-info")).toHaveText(
    "Quy Regression",
  )

  await page.goto("/vn/account/addresses")
  await expect(page.getByTestId("addresses-page-wrapper")).toBeVisible()
  await page.getByTestId("add-address-button").click()
  const addModal = page.getByTestId("add-address-modal")
  await expect(addModal).toBeVisible()
  await addModal.getByTestId("first-name-input").fill("Quy")
  await addModal.getByTestId("last-name-input").fill("Regression")
  await addModal.getByTestId("address-1-input").fill("123 Le Loi")
  await addModal.getByTestId("address-2-input").fill("Ben Nghe")
  await addModal.getByTestId("postal-code-input").fill("700000")
  await addModal.getByTestId("city-input").fill("Quan 1")
  await addModal.getByTestId("state-input").fill("Ho Chi Minh")
  await addModal.getByTestId("country-select").selectOption("vn")
  await addModal.getByTestId("phone-input").fill("0901234567")
  await addModal.getByTestId("save-button").click()

  const address = page.getByTestId("address-container").filter({ hasText: "123 Le Loi" })
  await expect(address).toBeVisible()
  await address.getByTestId("address-edit-button").click()
  const editModal = page.getByTestId("edit-address-modal")
  await expect(editModal).toBeVisible()
  await editModal.getByTestId("address-1-input").fill("456 Nguyen Hue")
  await editModal.getByTestId("save-button").click()
  const updatedAddress = page.getByTestId("address-container").filter({ hasText: "456 Nguyen Hue" })
  await expect(updatedAddress).toBeVisible()
  await updatedAddress.getByTestId("address-delete-button").click()
  await expect(updatedAddress).toHaveCount(0)
})
